CREATE TABLE IF NOT EXISTS refresh_tokens (
    refresh_token_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    token_hash varchar(64) NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL,
    user_agent varchar(255),
    ip_address varchar(45),
    family_id varchar(36),
    remember_me boolean,
    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash)
);

ALTER TABLE refresh_tokens ADD COLUMN IF NOT EXISTS family_id varchar(36);
ALTER TABLE refresh_tokens ADD COLUMN IF NOT EXISTS remember_me boolean;
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_family_id ON refresh_tokens (family_id);
