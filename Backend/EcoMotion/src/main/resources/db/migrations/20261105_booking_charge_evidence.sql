-- Additive migration; legacy booking_charge.evidence_url remains untouched.
CREATE TABLE IF NOT EXISTS booking_charge_evidence (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_charge_id bigint NOT NULL REFERENCES booking_charge(id) ON DELETE RESTRICT,
    secure_url varchar(1000) NOT NULL,
    public_id varchar(500) NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_charge_evidence_charge ON booking_charge_evidence (booking_charge_id);
