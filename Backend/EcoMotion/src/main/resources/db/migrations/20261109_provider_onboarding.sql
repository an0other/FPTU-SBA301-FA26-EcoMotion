BEGIN;
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS email_verified_at timestamptz,
    ADD COLUMN IF NOT EXISTS phone_verified_at timestamptz,
    ADD COLUMN IF NOT EXISTS terms_accepted_at timestamptz;

CREATE TABLE IF NOT EXISTS provider_application (
    user_id bigint PRIMARY KEY REFERENCES users(id),
    status varchar(30) NOT NULL DEFAULT 'DRAFT',
    profile_json text,
    submitted_at timestamptz,
    reviewed_at timestamptz,
    reviewed_by bigint REFERENCES users(id),
    reason_code varchar(100),
    submitted_identity_id bigint REFERENCES person_identity(id),
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT ck_provider_application_status CHECK (status IN ('DRAFT','SUBMITTED','NEEDS_CHANGES','REJECTED','APPROVED'))
);
CREATE INDEX IF NOT EXISTS idx_provider_application_review ON provider_application(status, submitted_at, user_id);

CREATE TABLE IF NOT EXISTS provider_application_review (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES provider_application(user_id),
    application_version bigint NOT NULL,
    admin_id bigint NOT NULL REFERENCES users(id),
    decision varchar(30) NOT NULL,
    reason_code varchar(100),
    reviewed_at timestamptz NOT NULL,
    profile_snapshot_json text,
    CONSTRAINT ck_provider_review_decision CHECK (decision IN ('APPROVE','NEEDS_CHANGES','REJECT','REOPEN'))
);
COMMIT;
