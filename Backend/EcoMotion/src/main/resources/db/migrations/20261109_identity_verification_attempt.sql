BEGIN;

CREATE TABLE IF NOT EXISTS identity_verification_attempt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid NOT NULL,
    user_id bigint NOT NULL,
    active_user_id bigint,
    role varchar(20) NOT NULL,
    status varchar(30) NOT NULL,
    operation_id uuid,
    processing_stage varchar(20),
    operation_started_at timestamptz,
    document_revision integer NOT NULL DEFAULT 0,
    front_key varchar(100),
    back_key varchar(100),
    video_key varchar(100),
    front_sha256 varchar(64),
    back_sha256 varchar(64),
    document_json text,
    video_json text,
    last_error_code varchar(100),
    expires_at timestamptz NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_identity_attempt_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT uk_identity_attempt_public UNIQUE (public_id),
    CONSTRAINT uk_identity_attempt_active_user UNIQUE (active_user_id),
    CONSTRAINT ck_identity_attempt_owner CHECK (active_user_id IS NULL OR active_user_id = user_id),
    CONSTRAINT ck_identity_attempt_role CHECK (role IN ('RENTER', 'PROVIDER')),
    CONSTRAINT ck_identity_attempt_status CHECK (
        status IN ('DRAFT', 'PROCESSING', 'DOCUMENT_READY', 'READY_TO_SUBMIT', 'ERROR', 'CANCELLED', 'EXPIRED')
    )
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'person_identity'::regclass AND conname = 'fk_person_identity_approved_attempt'
    ) THEN
        ALTER TABLE person_identity ADD CONSTRAINT fk_person_identity_approved_attempt
            FOREIGN KEY (approved_attempt_id) REFERENCES identity_verification_attempt(id);
    END IF;
END;
$$;

COMMIT;
