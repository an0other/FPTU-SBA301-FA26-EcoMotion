BEGIN;
CREATE TABLE IF NOT EXISTS driving_license_submission (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id uuid NOT NULL UNIQUE,
 renter_id bigint NOT NULL REFERENCES renter(id),
 version bigint NOT NULL DEFAULT 0,
 status varchar(30) NOT NULL CHECK (status IN ('READY_TO_SUBMIT','SUBMITTED','APPROVED','NEEDS_CHANGES','REJECTED','CANCELLED')),
 no_qr_declared boolean NOT NULL DEFAULT false,
 document_json text NOT NULL,
 evidence_json text NOT NULL,
 history_json text NOT NULL,
 front_path varchar(500) NOT NULL,
 back_path varchar(500) NOT NULL,
 created_at timestamptz NOT NULL,
 submitted_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_license_submission_queue ON driving_license_submission(status, submitted_at, id);
CREATE INDEX IF NOT EXISTS idx_license_submission_renter ON driving_license_submission(renter_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_license_submission_active ON driving_license_submission(renter_id)
 WHERE status IN ('READY_TO_SUBMIT','SUBMITTED');
COMMIT;
