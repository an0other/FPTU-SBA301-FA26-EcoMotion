-- Run once, before deploying mixed rental pricing. Never re-run schema.sql on an existing DB.
BEGIN;
ALTER TABLE booking ADD COLUMN IF NOT EXISTS planned_end_at timestamptz;
CREATE TABLE IF NOT EXISTS booking_pricing_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES booking(id) ON DELETE CASCADE,
    plan_id bigint NOT NULL REFERENCES rental_plan(id) ON DELETE RESTRICT,
    plan_type varchar(20) NOT NULL CHECK (plan_type IN ('HOURLY','DAILY','MONTHLY','YEARLY')),
    slot_length_minutes integer NOT NULL CHECK (slot_length_minutes > 0),
    unit_price numeric(14,2) NOT NULL CHECK (unit_price >= 0),
    quantity integer NOT NULL CHECK (quantity > 0)
);
CREATE INDEX IF NOT EXISTS idx_booking_pricing_item_booking ON booking_pricing_item(booking_id);

-- Only trust a single base-rental charge and its immutable snapshot.
INSERT INTO booking_pricing_item(booking_id, plan_id, plan_type, slot_length_minutes, unit_price, quantity)
SELECT b.id, b.plan_id, s.plan_type, s.slot_length_minutes, c.unit_price, c.quantity
FROM booking b JOIN booking_policy_snapshot s ON s.booking_id=b.id
JOIN booking_charge c ON c.booking_id=b.id AND c.charge_type='BASE_RENTAL'
WHERE c.quantity > 0 AND c.unit_price * c.quantity = c.amount
AND NOT EXISTS(SELECT 1 FROM booking_charge other WHERE other.booking_id=b.id
               AND other.charge_type='BASE_RENTAL' AND other.id<>c.id)
AND NOT EXISTS(SELECT 1 FROM booking_pricing_item i WHERE i.booking_id=b.id);

UPDATE booking b SET planned_end_at = (
    SELECT vs.end_at FROM vehicle_schedule vs WHERE vs.booking_id=b.id
      AND vs.type='BOOKED' AND vs.is_extension=false
    ORDER BY CASE WHEN vs.status IN ('ACTIVE','HELD') THEN 0 ELSE 1 END, vs.id DESC LIMIT 1
) WHERE b.planned_end_at IS NULL;
UPDATE booking b SET planned_end_at = b.pickup_time + make_interval(mins => i.slot_length_minutes * i.quantity)
FROM booking_pricing_item i WHERE i.booking_id=b.id AND b.planned_end_at IS NULL;

DO $$
DECLARE unresolved text;
BEGIN
    SELECT string_agg(b.booking_code, ', ') INTO unresolved FROM booking b
    WHERE b.planned_end_at IS NULL OR b.planned_end_at <= b.pickup_time
       OR NOT EXISTS(SELECT 1 FROM booking_pricing_item i WHERE i.booking_id=b.id);
    IF unresolved IS NOT NULL THEN
        RAISE EXCEPTION 'Cannot migrate booking duration/pricing; review bookings: %', unresolved;
    END IF;
    IF EXISTS(SELECT 1 FROM rental_plan WHERE plan_type='HOURLY'
              AND (slot_length_minutes < 60 OR slot_length_minutes % 60 <> 0)) THEN
        RAISE EXCEPTION 'Hourly plan duration must contain a whole number of hours';
    END IF;
END $$;
ALTER TABLE booking ALTER COLUMN planned_end_at SET NOT NULL;
ALTER TABLE booking ADD CONSTRAINT ck_booking_planned_end CHECK (planned_end_at > pickup_time);
UPDATE rental_plan SET slot_price=round(slot_price * 60 / slot_length_minutes, 0),
                       slot_length_minutes=60, updated_at=now()
WHERE plan_type='HOURLY' AND slot_length_minutes<>60;
COMMIT;
