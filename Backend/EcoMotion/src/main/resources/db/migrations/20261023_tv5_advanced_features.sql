-- 1. Bổ sung các cột trên bảng booking
ALTER TABLE booking ADD COLUMN IF NOT EXISTS assignment_mode VARCHAR(30) DEFAULT 'AUTO_SUGGEST';
ALTER TABLE booking ADD COLUMN IF NOT EXISTS reassign_count INTEGER DEFAULT 0;
ALTER TABLE booking ADD COLUMN IF NOT EXISTS assignment_expires_at TIMESTAMPTZ;

-- 2. Bổ sung các cột trên bảng provider
ALTER TABLE provider ADD COLUMN IF NOT EXISTS default_assignment_mode VARCHAR(30) DEFAULT 'AUTO_SUGGEST';

-- 3. Bổ sung các cột VNPAY trên payment_transaction
ALTER TABLE payment_transaction ADD COLUMN IF NOT EXISTS vnp_txn_ref VARCHAR(100);
ALTER TABLE payment_transaction ADD COLUMN IF NOT EXISTS vnp_transaction_no VARCHAR(100);
ALTER TABLE payment_transaction ADD COLUMN IF NOT EXISTS vnp_bank_code VARCHAR(20);
ALTER TABLE payment_transaction ADD COLUMN IF NOT EXISTS vnp_card_type VARCHAR(50);
ALTER TABLE payment_transaction ADD COLUMN IF NOT EXISTS vnp_pay_date VARCHAR(50);
ALTER TABLE payment_transaction ADD COLUMN IF NOT EXISTS vnp_response_code VARCHAR(20);

CREATE INDEX IF NOT EXISTS idx_payment_vnp_txn_ref ON payment_transaction (vnp_txn_ref);

-- 4. Bảng driver_assignment (lưu lịch sử phân công, phản hồi và tái phân công)
CREATE TABLE IF NOT EXISTS driver_assignment (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id           BIGINT NOT NULL REFERENCES booking (id) ON DELETE CASCADE,
    driver_id            BIGINT NOT NULL REFERENCES driver (id) ON DELETE RESTRICT,
    status               VARCHAR(30) NOT NULL DEFAULT 'PENDING_RESPONSE',
    rejection_reason     VARCHAR(50),
    rejection_note       VARCHAR(500),
    assigned_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at         TIMESTAMPTZ,
    expires_at           TIMESTAMPTZ,
    round_number         INTEGER NOT NULL DEFAULT 1,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_driver_assignment_status CHECK (status IN (
        'PENDING_RESPONSE', 'ACCEPTED', 'REJECTED', 'TIMEOUT', 'RECALLED'
    ))
);

CREATE INDEX IF NOT EXISTS idx_driver_assignment_booking ON driver_assignment (booking_id);
CREATE INDEX IF NOT EXISTS idx_driver_assignment_driver ON driver_assignment (driver_id);
CREATE INDEX IF NOT EXISTS idx_driver_assignment_status ON driver_assignment (status);

-- 5. Bảng trip_incident (báo cáo và xử lý sự cố tài xế)
CREATE TABLE IF NOT EXISTS trip_incident (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id           BIGINT NOT NULL REFERENCES booking (id) ON DELETE CASCADE,
    driver_id            BIGINT NOT NULL REFERENCES driver (id) ON DELETE RESTRICT,
    incident_type        VARCHAR(50) NOT NULL,
    description          VARCHAR(1000) NOT NULL,
    urgency              VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    status               VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    location_latitude    FLOAT8,
    location_longitude   FLOAT8,
    evidence_urls        VARCHAR(2000),
    resolution_note      VARCHAR(1000),
    created_by_id        BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    resolved_by_id       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at          TIMESTAMPTZ,
    CONSTRAINT ck_trip_incident_urgency CHECK (urgency IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_trip_incident_status CHECK (status IN ('OPEN', 'INVESTIGATING', 'RESOLVED', 'CANCELLED'))
);

CREATE INDEX IF NOT EXISTS idx_trip_incident_booking ON trip_incident (booking_id);
CREATE INDEX IF NOT EXISTS idx_trip_incident_driver ON trip_incident (driver_id);
CREATE INDEX IF NOT EXISTS idx_trip_incident_status ON trip_incident (status);

-- 6. Bảng trip_evidence (ảnh bằng chứng bàn giao, điểm đón, kết thúc)
CREATE TABLE IF NOT EXISTS trip_evidence (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id           BIGINT NOT NULL REFERENCES booking (id) ON DELETE CASCADE,
    driver_id            BIGINT REFERENCES driver (id) ON DELETE RESTRICT,
    uploaded_by_id       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    evidence_type        VARCHAR(50) NOT NULL,
    image_url            VARCHAR(500) NOT NULL,
    cloudinary_public_id VARCHAR(255),
    original_file_name   VARCHAR(255),
    file_size            BIGINT,
    width                INT,
    height               INT,
    note                 VARCHAR(500),
    recorded_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_trip_evidence_type CHECK (evidence_type IN (
        'PICKUP_ARRIVAL', 'VEHICLE_HANDOVER', 'PRE_TRIP_CONDITION', 'POST_TRIP_CONDITION',
        'INCIDENT', 'TRIP_COMPLETION', 'INCIDENT_PROOF', 'OTHER'
    ))
);

ALTER TABLE trip_evidence ADD COLUMN IF NOT EXISTS cloudinary_public_id VARCHAR(255);
ALTER TABLE trip_evidence ADD COLUMN IF NOT EXISTS original_file_name VARCHAR(255);
ALTER TABLE trip_evidence ADD COLUMN IF NOT EXISTS file_size BIGINT;
ALTER TABLE trip_evidence ADD COLUMN IF NOT EXISTS width INT;
ALTER TABLE trip_evidence ADD COLUMN IF NOT EXISTS height INT;
ALTER TABLE trip_evidence ADD COLUMN IF NOT EXISTS uploaded_by_id BIGINT REFERENCES users (id) ON DELETE SET NULL;
ALTER TABLE trip_evidence ALTER COLUMN driver_id DROP NOT NULL;

CREATE INDEX IF NOT EXISTS idx_trip_evidence_booking ON trip_evidence (booking_id);
CREATE INDEX IF NOT EXISTS idx_trip_evidence_driver ON trip_evidence (driver_id);
CREATE INDEX IF NOT EXISTS idx_trip_evidence_uploader ON trip_evidence (uploaded_by_id);


-- 7. Bảng refund_request (quy trình hoàn tiền có đối soát và chống trùng)
CREATE TABLE IF NOT EXISTS refund_request (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id           BIGINT NOT NULL REFERENCES booking (id) ON DELETE RESTRICT,
    payment_transaction_id BIGINT REFERENCES payment_transaction (id) ON DELETE SET NULL,
    amount               NUMERIC(14,2) NOT NULL,
    reason               VARCHAR(500) NOT NULL,
    evidence_url         VARCHAR(500),
    status               VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    requested_by_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    approved_by_id       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    rejection_reason     VARCHAR(500),
    gateway_refund_ref   VARCHAR(100),
    version              BIGINT NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_refund_request_status CHECK (status IN (
        'REQUESTED', 'UNDER_REVIEW', 'APPROVED', 'PROCESSING', 'REFUNDED', 'REJECTED', 'FAILED', 'PENDING_RECONCILIATION'
    )),
    CONSTRAINT ck_refund_request_amount CHECK (amount > 0)
);

CREATE INDEX IF NOT EXISTS idx_refund_request_booking ON refund_request (booking_id);
CREATE INDEX IF NOT EXISTS idx_refund_request_status ON refund_request (status);
