BEGIN;
CREATE TABLE IF NOT EXISTS yearly_workflow (
    booking_id bigint PRIMARY KEY REFERENCES booking(id),
    version bigint NOT NULL DEFAULT 0,
    stage varchar(2000),
    return_mode varchar(2000),
    settlement_note varchar(2000),
    refund_reference varchar(2000),
    terms_accepted boolean NOT NULL DEFAULT false,
    grace_days integer NOT NULL DEFAULT 0,
    annual_km bigint,
    current_initial_km bigint,
    final_km bigint,
    return_evidence_id bigint,
    total_km bigint,
    settlement_evidence_id bigint,
    refund_evidence_id bigint,
    completed_km bigint NOT NULL DEFAULT 0,
    returned_on date,
    failure_on date,
    excess_km_rate numeric(14,2) DEFAULT 0,
    late_daily_rate numeric(14,2) DEFAULT 0,
    rounding_unit numeric(14,2) DEFAULT 0,
    rent_due numeric(14,2) DEFAULT 0,
    early_fee numeric(14,2) DEFAULT 0,
    late_fee numeric(14,2) DEFAULT 0,
    excess_km_fee numeric(14,2) DEFAULT 0,
    other_charges numeric(14,2) DEFAULT 0,
    rent_paid numeric(14,2) DEFAULT 0,
    deposit_held numeric(14,2) DEFAULT 0,
    deposit_deduction numeric(14,2) DEFAULT 0,
    balance_due numeric(14,2) DEFAULT 0,
    rent_refund numeric(14,2) DEFAULT 0,
    deposit_refund numeric(14,2) DEFAULT 0
);
CREATE TABLE IF NOT EXISTS yearly_incident (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    booking_id bigint REFERENCES booking(id),
    evidence_id bigint,
    transfer_evidence_id bigint,
    request_id varchar(2000),
    category varchar(2000),
    description varchar(2000),
    status varchar(2000),
    outcome varchar(2000),
    resolution_note varchar(2000),
    bank_reference varchar(2000),
    occurred_on date,
    invoice_amount numeric(14,2) DEFAULT 0,
    approved_amount numeric(14,2) DEFAULT 0,
    CONSTRAINT uk_yearly_incident_request UNIQUE (booking_id, request_id)
);
CREATE TABLE IF NOT EXISTS yearly_replacement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    booking_id bigint REFERENCES booking(id),
    incident_id bigint,
    old_vehicle_id bigint,
    new_vehicle_id bigint,
    old_final_km bigint,
    new_initial_km bigint,
    old_evidence_id bigint,
    new_evidence_id bigint,
    planned_on date,
    exchanged_on date,
    status varchar(2000)
);
CREATE INDEX IF NOT EXISTS ix_yearly_incident_booking ON yearly_incident(booking_id);
CREATE INDEX IF NOT EXISTS ix_yearly_replacement_booking ON yearly_replacement(booking_id);
ALTER TABLE yearly_workflow ADD COLUMN IF NOT EXISTS contract_total numeric(14,2);
ALTER TABLE yearly_workflow ADD COLUMN IF NOT EXISTS security_deposit numeric(14,2);
COMMIT;
