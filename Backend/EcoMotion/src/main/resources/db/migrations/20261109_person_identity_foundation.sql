BEGIN;

CREATE TABLE IF NOT EXISTS person_identity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cccd_ciphertext varchar(255) NOT NULL,
    cccd_fingerprint varchar(64) NOT NULL,
    fingerprint_key_version integer NOT NULL,
    full_name varchar(150) NOT NULL,
    date_of_birth date NOT NULL,
    gender varchar(10),
    address varchar(500),
    document_expiry date,
    status varchar(20) NOT NULL,
    verification_method varchar(30) NOT NULL,
    policy_version varchar(100) NOT NULL,
    approved_attempt_id bigint,
    verified_at timestamptz NOT NULL,
    reviewed_by bigint,
    reviewed_at timestamptz,
    version bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_person_identity_cccd_fingerprint UNIQUE (cccd_fingerprint),
    CONSTRAINT ck_person_identity_fingerprint CHECK (length(cccd_fingerprint) = 64 AND fingerprint_key_version > 0),
    CONSTRAINT ck_person_identity_status CHECK (status IN ('VERIFIED', 'SUSPENDED', 'REVOKED')),
    CONSTRAINT ck_person_identity_method CHECK (verification_method IN ('AUTOMATED_POLICY', 'ADMIN_REVIEW', 'DEMO_SEED')),
    CONSTRAINT ck_person_identity_review CHECK (
        verification_method <> 'ADMIN_REVIEW' OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    )
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS identity_id bigint;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'users'::regclass AND conname = 'fk_users_identity'
    ) THEN
        ALTER TABLE users ADD CONSTRAINT fk_users_identity
            FOREIGN KEY (identity_id) REFERENCES person_identity(id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'users'::regclass AND conname = 'uk_users_identity_role'
    ) THEN
        ALTER TABLE users ADD CONSTRAINT uk_users_identity_role UNIQUE (identity_id, role);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'users'::regclass AND conname = 'ck_users_identity_role'
    ) THEN
        ALTER TABLE users ADD CONSTRAINT ck_users_identity_role
            CHECK (identity_id IS NULL OR role IN ('RENTER', 'PROVIDER'));
    END IF;
END;
$$;

COMMIT;
