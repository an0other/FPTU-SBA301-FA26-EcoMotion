-- Remove platform commission and provider payout from the payment model.
-- Forward-only. Does not edit any earlier migration.
--
-- Scope of the new payment model: DEPOSIT, FINAL_PAYMENT (VNPAY) and REFUND (manual bank transfer).
--
-- Safety rules:
--   1. The migration REFUSES to run if any PAYOUT transaction or payout amount exists. Such rows are
--      financial history and must be archived or reconciled by a person before this runs.
--   2. Each provider's commission_rate is copied to provider_commission_rate_archive before the column is dropped,
--      so the configured rate remains available for audit.
-- Take a backup before running on any database that holds real money data.

BEGIN;

DO $$
DECLARE
    payout_rows bigint;
    payout_amount_rows bigint := 0;
BEGIN
    SELECT COUNT(*) INTO payout_rows FROM payment_transaction WHERE type = 'PAYOUT';
    -- The payout columns are gone after a successful run; check them only while they exist (re-runnable).
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'payment_transaction' AND column_name = 'payout_gross_amount') THEN
        EXECUTE 'SELECT COUNT(*) FROM payment_transaction WHERE payout_gross_amount IS NOT NULL OR payout_fee_amount IS NOT NULL'
            INTO payout_amount_rows;
    END IF;
    IF payout_rows > 0 OR payout_amount_rows > 0 THEN
        RAISE EXCEPTION 'Refusing to remove payout schema: % PAYOUT rows and % rows with payout amounts exist. Archive and reconcile them first.',
            payout_rows, payout_amount_rows;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS provider_commission_rate_archive (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id     bigint        NOT NULL,
    commission_rate numeric(6,4)  NOT NULL,
    archived_at     timestamptz   NOT NULL DEFAULT now(),
    reason          varchar(100)  NOT NULL DEFAULT '20261109_remove_commission_and_payout'
);

-- Archive only while the column still exists, so a re-run cannot duplicate archive rows.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'provider' AND column_name = 'commission_rate') THEN
        INSERT INTO provider_commission_rate_archive (provider_id, commission_rate)
        SELECT id, commission_rate FROM provider;
    END IF;
END $$;

ALTER TABLE provider DROP CONSTRAINT IF EXISTS ck_provider_commission;
ALTER TABLE provider DROP COLUMN IF EXISTS commission_rate;

ALTER TABLE payment_transaction
    DROP COLUMN IF EXISTS payout_gross_amount,
    DROP COLUMN IF EXISTS payout_fee_amount;

ALTER TABLE payment_transaction DROP CONSTRAINT IF EXISTS ck_payment_type;
ALTER TABLE payment_transaction
    ADD CONSTRAINT ck_payment_type CHECK (type IN ('DEPOSIT_PAY', 'UPFRONT_PAY', 'SETTLEMENT', 'REFUND'));

ALTER TABLE payment_transaction DROP CONSTRAINT IF EXISTS ck_payment_direction_by_type;
ALTER TABLE payment_transaction
    ADD CONSTRAINT ck_payment_direction_by_type CHECK (
        (type IN ('DEPOSIT_PAY', 'UPFRONT_PAY', 'SETTLEMENT') AND direction = 'IN')
        OR (type IN ('REFUND') AND direction = 'OUT')
    );

COMMIT;
