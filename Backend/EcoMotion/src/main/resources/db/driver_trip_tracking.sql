ALTER TABLE booking ADD COLUMN IF NOT EXISTS assigned_at timestamptz;
ALTER TABLE booking ADD COLUMN IF NOT EXISTS driver_confirmed_at timestamptz;
ALTER TABLE booking ADD COLUMN IF NOT EXISTS actual_arrived_at timestamptz;
ALTER TABLE booking ADD COLUMN IF NOT EXISTS version bigint NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS vehicle_location (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      bigint       NOT NULL,
    driver_id       bigint       NOT NULL,
    vehicle_id      bigint       NOT NULL,
    latitude        float8       NOT NULL,
    longitude       float8       NOT NULL,
    accuracy_meters float8,
    recorded_at     timestamptz  NOT NULL,
    received_at     timestamptz  NOT NULL DEFAULT now(),
    created_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_vehicle_location_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE CASCADE,
    CONSTRAINT fk_vehicle_location_driver FOREIGN KEY (driver_id) REFERENCES driver (id) ON DELETE RESTRICT,
    CONSTRAINT fk_vehicle_location_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicle (id) ON DELETE RESTRICT,
    CONSTRAINT ck_vehicle_location_coords CHECK (
        latitude >= -90.0 AND latitude <= 90.0 AND longitude >= -180.0 AND longitude <= 180.0
    ),
    CONSTRAINT ck_vehicle_location_accuracy CHECK (
        accuracy_meters IS NULL OR accuracy_meters >= 0
    )
);

CREATE INDEX IF NOT EXISTS idx_vehicle_location_booking_received
    ON vehicle_location (booking_id, received_at DESC);

CREATE INDEX IF NOT EXISTS idx_vehicle_location_vehicle_received
    ON vehicle_location (vehicle_id, received_at DESC);
