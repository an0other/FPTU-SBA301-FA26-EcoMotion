CREATE TABLE dispute (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id   bigint       NOT NULL,
    charge_id    bigint,
    raised_by    bigint       NOT NULL,
    handled_by   bigint,
    category     varchar(30)  NOT NULL,
    status       varchar(20)  NOT NULL DEFAULT 'OPEN',
    resolution   varchar(1000),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_dispute_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE RESTRICT,
    CONSTRAINT fk_dispute_charge FOREIGN KEY (charge_id) REFERENCES booking_charge (id) ON DELETE RESTRICT,
    CONSTRAINT fk_dispute_raised_by FOREIGN KEY (raised_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_dispute_handled_by FOREIGN KEY (handled_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_dispute_category CHECK (category IN (
        'CHARGE', 'SERVICE_QUALITY', 'DEPOSIT_REFUND', 'TRIP_NOT_CONFIRMED'
    )),
    CONSTRAINT ck_dispute_status CHECK (status IN ('OPEN', 'IN_REVIEW', 'RESOLVED', 'REJECTED')),
    CONSTRAINT ck_dispute_charge_category CHECK (
        (category = 'CHARGE' AND charge_id IS NOT NULL)
        OR (category <> 'CHARGE' AND charge_id IS NULL)
    ),
    CONSTRAINT ck_dispute_handler CHECK (status = 'OPEN' OR handled_by IS NOT NULL),
    CONSTRAINT ck_dispute_resolution CHECK (
        status NOT IN ('RESOLVED', 'REJECTED') OR resolution IS NOT NULL
    )
);

CREATE INDEX idx_dispute_booking_id ON dispute (booking_id);
CREATE INDEX idx_dispute_charge_id ON dispute (charge_id);
CREATE INDEX idx_dispute_raised_by ON dispute (raised_by);
CREATE INDEX idx_dispute_handled_by ON dispute (handled_by);
CREATE INDEX idx_dispute_status ON dispute (status);

