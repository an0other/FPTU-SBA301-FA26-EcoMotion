CREATE FUNCTION enforce_profile_role()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    actual_role varchar(20);
    expected_role varchar(20);
BEGIN
    SELECT role INTO actual_role FROM users WHERE id = NEW.user_id;
    IF actual_role IS NULL THEN
        RAISE EXCEPTION 'user % does not exist', NEW.user_id;
    END IF;

    expected_role := CASE TG_TABLE_NAME
        WHEN 'provider' THEN 'PROVIDER'
        WHEN 'renter' THEN 'RENTER'
        WHEN 'driver' THEN 'DRIVER'
    END;

    IF actual_role <> expected_role THEN
        RAISE EXCEPTION '% profile requires users.role = %', TG_TABLE_NAME, expected_role;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION prevent_vehicle_identity_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.chassis_no IS DISTINCT FROM OLD.chassis_no
        OR NEW.engine_no IS DISTINCT FROM OLD.engine_no THEN
        RAISE EXCEPTION 'chassis_no and engine_no are immutable; create a new vehicle';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION reject_snapshot_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'booking_policy_snapshot is immutable';
END;
$$;

