CREATE INDEX idx_users_role_status ON users (role, status);

CREATE TABLE provider (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               bigint        NOT NULL,
    provider_type         varchar(20)   NOT NULL,
    display_name          varchar(150)  NOT NULL,
    hotline               varchar(20)   NOT NULL,
    depot_address         varchar(500)  NOT NULL,
    commission_rate       numeric(6,4)  NOT NULL,
    deposit_ratio         numeric(6,4)  NOT NULL,
    bank_name             varchar(150),
    bank_account_no       varchar(50),
    bank_account_holder   varchar(150),
    business_license_no   varchar(50),
    tax_code              varchar(20),
    status                varchar(20)   NOT NULL DEFAULT 'PENDING',
    rating_avg            numeric(3,2)  NOT NULL DEFAULT 0,
    rating_count          integer       NOT NULL DEFAULT 0,
    created_at            timestamptz   NOT NULL DEFAULT now(),
    updated_at            timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT uk_provider_user_id UNIQUE (user_id),
    CONSTRAINT fk_provider_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_provider_type CHECK (provider_type IN ('INDIVIDUAL', 'BUSINESS')),
    CONSTRAINT ck_provider_status CHECK (status IN ('PENDING', 'APPROVED', 'LOCKED')),
    CONSTRAINT ck_provider_business_fields CHECK (
        (
            provider_type = 'INDIVIDUAL'
            AND business_license_no IS NULL
            AND tax_code IS NULL
        )
        OR (
            provider_type = 'BUSINESS'
            AND business_license_no IS NOT NULL
            AND tax_code IS NOT NULL
        )
    ),
    CONSTRAINT ck_provider_commission CHECK (commission_rate >= 0 AND commission_rate <= 1),
    CONSTRAINT ck_provider_deposit_ratio CHECK (deposit_ratio >= 0 AND deposit_ratio <= 1),
    CONSTRAINT ck_provider_rating CHECK (
        rating_count >= 0
        AND rating_avg >= 0
        AND rating_avg <= 5
        AND (rating_count > 0 OR rating_avg = 0)
    ),
    CONSTRAINT ck_provider_bank CHECK (
        (bank_name IS NULL AND bank_account_no IS NULL AND bank_account_holder IS NULL)
        OR (bank_name IS NOT NULL AND bank_account_no IS NOT NULL AND bank_account_holder IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uk_provider_tax_code
    ON provider (tax_code) WHERE tax_code IS NOT NULL;
CREATE UNIQUE INDEX uk_provider_business_license
    ON provider (business_license_no) WHERE business_license_no IS NOT NULL;
CREATE INDEX idx_provider_status ON provider (status);

