    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    bigint        NOT NULL,
    charge_type   varchar(20)   NOT NULL,
    description   varchar(500)  NOT NULL,
    quantity      integer,
    unit_price    numeric(14,2) NOT NULL,
    applied_rate  numeric(6,4),
    amount        numeric(14,2) NOT NULL,
    created_by    bigint        NOT NULL,
    is_waived     boolean       NOT NULL DEFAULT false,
    evidence_url  varchar(500),
    created_at    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_booking_charge_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_charge_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_booking_charge_type CHECK (charge_type IN (
        'BASE_RENTAL', 'DEPOSIT', 'OVERTIME', 'WAITING', 'WEEKEND', 'OUT_OF_RADIUS'
    )),
    CONSTRAINT ck_booking_charge_money CHECK (unit_price >= 0 AND amount >= 0),
    CONSTRAINT ck_booking_charge_applied_rate CHECK (applied_rate IS NULL OR applied_rate >= 0),
    CONSTRAINT ck_booking_charge_quantity CHECK (
        (charge_type IN ('DEPOSIT', 'WEEKEND') AND quantity IS NULL)
        OR (
            charge_type IN ('BASE_RENTAL', 'OVERTIME', 'WAITING', 'OUT_OF_RADIUS')
            AND quantity IS NOT NULL
            AND quantity > 0
        )
    )
);

CREATE INDEX idx_booking_charge_booking_id ON booking_charge (booking_id);
CREATE INDEX idx_booking_charge_booking_type ON booking_charge (booking_id, charge_type);
CREATE INDEX idx_booking_charge_created_by ON booking_charge (created_by);

CREATE TABLE payment_transaction (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    bigint        NOT NULL,
    charge_id     bigint,
    type          varchar(20)   NOT NULL,
    amount        numeric(14,2) NOT NULL,
    direction     varchar(3)    NOT NULL,
    method        varchar(20)   NOT NULL,
    gateway_ref   varchar(100),
    status        varchar(20)   NOT NULL DEFAULT 'PENDING',
    receipt_url   varchar(500),
    paid_at       timestamptz,
    created_at    timestamptz   NOT NULL DEFAULT now(),
    updated_at    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_payment_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment_charge FOREIGN KEY (charge_id) REFERENCES booking_charge (id) ON DELETE RESTRICT,
    CONSTRAINT ck_payment_type CHECK (type IN ('DEPOSIT_PAY', 'UPFRONT_PAY', 'SETTLEMENT', 'REFUND', 'PAYOUT')),
    CONSTRAINT ck_payment_direction CHECK (direction IN ('IN', 'OUT')),
    CONSTRAINT ck_payment_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'E_WALLET', 'CARD')),
    CONSTRAINT ck_payment_status CHECK (status IN ('PENDING', 'PAID', 'FAILED')),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_paid_at CHECK (status <> 'PAID' OR paid_at IS NOT NULL),
    CONSTRAINT ck_payment_direction_by_type CHECK (
        (type IN ('DEPOSIT_PAY', 'UPFRONT_PAY', 'SETTLEMENT') AND direction = 'IN')
        OR (type IN ('REFUND', 'PAYOUT') AND direction = 'OUT')
    )
);

CREATE INDEX idx_payment_booking_id ON payment_transaction (booking_id);
CREATE INDEX idx_payment_charge_id ON payment_transaction (charge_id);
CREATE INDEX idx_payment_type_status ON payment_transaction (type, status);
CREATE UNIQUE INDEX uk_payment_gateway_ref ON payment_transaction (gateway_ref) WHERE gateway_ref IS NOT NULL;

