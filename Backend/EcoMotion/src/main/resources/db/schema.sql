    actual_end_at           timestamptz,
    renter_confirmed_at     timestamptz,
    provider_confirmed_at   timestamptz,
    pickup_address          varchar(500)  NOT NULL,
    pickup_time             timestamptz   NOT NULL,
    passenger_count         integer       NOT NULL,
    contract_url            varchar(500),
    total_amount            numeric(14,2) NOT NULL,
    cancelled_by            bigint,
    cancel_reason           varchar(40),
    cancelled_at            timestamptz,
    created_at              timestamptz   NOT NULL DEFAULT now(),
    updated_at              timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT uk_booking_code UNIQUE (booking_code),
    CONSTRAINT fk_booking_renter FOREIGN KEY (renter_id) REFERENCES renter (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicle (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_plan FOREIGN KEY (plan_id) REFERENCES rental_plan (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_driver FOREIGN KEY (driver_id) REFERENCES driver (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_cancelled_by FOREIGN KEY (cancelled_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_booking_status CHECK (status IN (
        'PENDING', 'REJECTED', 'ACCEPTED', 'CONFIRMED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'
    )),
    CONSTRAINT ck_booking_cancel_reason CHECK (cancel_reason IS NULL OR cancel_reason IN (
        'RENTER_REQUEST', 'PROVIDER_NO_VEHICLE', 'PROVIDER_NO_DRIVER',
        'PREVIOUS_RENTER_OVERDUE', 'FORCE_MAJEURE', 'SYSTEM'
    )),
    CONSTRAINT ck_booking_cancel_fields CHECK (
        status <> 'CANCELLED'
        OR (cancelled_at IS NOT NULL AND cancel_reason IS NOT NULL AND cancelled_by IS NOT NULL)
    ),
    CONSTRAINT ck_booking_not_cancelled_fields CHECK (
        status = 'CANCELLED'
        OR (cancelled_at IS NULL AND cancel_reason IS NULL AND cancelled_by IS NULL)
    ),
    CONSTRAINT ck_booking_actual_range CHECK (
        actual_start_at IS NULL OR actual_end_at IS NULL OR actual_end_at >= actual_start_at
    ),
    CONSTRAINT ck_booking_passenger_count CHECK (passenger_count > 0),
    CONSTRAINT ck_booking_total_amount CHECK (total_amount >= 0)
);

