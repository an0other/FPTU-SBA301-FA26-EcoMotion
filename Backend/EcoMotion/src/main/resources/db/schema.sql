CREATE TABLE users (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           varchar(255) NOT NULL,
    phone           varchar(20)  NOT NULL,
    password_hash   varchar(255) NOT NULL,
    full_name       varchar(150) NOT NULL,
    avatar_url      varchar(500),
    role            varchar(20)  NOT NULL,
    status          varchar(20)  NOT NULL DEFAULT 'PENDING',
    ekyc_status     varchar(20)  NOT NULL DEFAULT 'UNVERIFIED',
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_phone UNIQUE (phone),
    CONSTRAINT ck_users_role CHECK (role IN ('RENTER', 'PROVIDER', 'DRIVER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'LOCKED', 'PENDING')),
    CONSTRAINT ck_users_ekyc_status CHECK (ekyc_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED'))
