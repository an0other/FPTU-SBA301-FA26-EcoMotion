    id                                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id                          bigint        NOT NULL,
    plan_type                           varchar(20)   NOT NULL,
    slot_length_minutes                 integer       NOT NULL,
    slot_price                          numeric(14,2) NOT NULL,
    upfront_amount                      numeric(14,2),
    status                              varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    allowed_overtime_minutes            integer,
    overtime_surcharge_ratio            numeric(6,4),
    free_radius_km                      integer,
    out_of_radius_rate                  numeric(14,2),
    waiting_free_minutes                integer,
    waiting_rate                        numeric(14,2),
    weekend_surcharge_ratio             numeric(6,4),
    hourly_to_daily_threshold_minutes   integer,
    created_at                          timestamptz   NOT NULL DEFAULT now(),
    updated_at                          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_rental_plan_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicle (id) ON DELETE RESTRICT,
    CONSTRAINT ck_rental_plan_type CHECK (plan_type IN ('HOURLY', 'DAILY', 'MONTHLY', 'YEARLY')),
    CONSTRAINT ck_rental_plan_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_rental_plan_slot CHECK (slot_length_minutes > 0 AND slot_price >= 0),
    CONSTRAINT ck_rental_plan_non_negative CHECK (
        (allowed_overtime_minutes IS NULL OR allowed_overtime_minutes >= 0)
        AND (overtime_surcharge_ratio IS NULL OR overtime_surcharge_ratio >= 0)
        AND (free_radius_km IS NULL OR free_radius_km >= 0)
        AND (out_of_radius_rate IS NULL OR out_of_radius_rate >= 0)
        AND (waiting_free_minutes IS NULL OR waiting_free_minutes >= 0)
        AND (waiting_rate IS NULL OR waiting_rate >= 0)
