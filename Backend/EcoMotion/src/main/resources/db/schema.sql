        AND (hourly_to_daily_threshold_minutes IS NULL OR hourly_to_daily_threshold_minutes > 0)
    ),
    CONSTRAINT ck_rental_plan_upfront CHECK (
        (plan_type = 'YEARLY' AND upfront_amount IS NOT NULL AND upfront_amount >= 0)
        OR (plan_type <> 'YEARLY' AND upfront_amount IS NULL)
    ),
    CONSTRAINT ck_rental_plan_hourly_threshold CHECK (
        plan_type = 'HOURLY' OR hourly_to_daily_threshold_minutes IS NULL
    ),
    CONSTRAINT ck_rental_plan_yearly_no_surcharge CHECK (
        plan_type <> 'YEARLY'
        OR (
            allowed_overtime_minutes IS NULL
            AND overtime_surcharge_ratio IS NULL
            AND free_radius_km IS NULL
            AND out_of_radius_rate IS NULL
            AND waiting_free_minutes IS NULL
            AND waiting_rate IS NULL
            AND weekend_surcharge_ratio IS NULL
            AND hourly_to_daily_threshold_minutes IS NULL
        )
    )
);

CREATE INDEX idx_rental_plan_vehicle_id ON rental_plan (vehicle_id);
CREATE UNIQUE INDEX uk_rental_plan_one_active
    ON rental_plan (vehicle_id, plan_type) WHERE status = 'ACTIVE';

