            allowed_overtime_minutes IS NULL
            AND overtime_surcharge_ratio IS NULL
            AND waiting_free_minutes IS NULL
            AND waiting_rate IS NULL
            AND weekend_surcharge_ratio IS NULL
            AND free_radius_km IS NULL
            AND out_of_radius_rate IS NULL
            AND hourly_to_daily_threshold_minutes IS NULL
